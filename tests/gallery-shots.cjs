// Скриншоты галереи, просмотрщика и ленты отзывов: node tests/gallery-shots.cjs <outDir> [scale]
const { chromium, devices } = require('playwright')
const [out, scale = '1'] = process.argv.slice(2)
;(async () => {
  const b = await chromium.launch()
  const init = () => { try { sessionStorage.setItem('exit_shown', '1') } catch {} }
  const d = await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: Number(scale) })
  await d.addInitScript(init)
  const p = await d.newPage()
  await p.goto('http://localhost:4173/', { waitUntil: 'networkidle' })
  await p.evaluate(() => document.getElementById('gallery').scrollIntoView())
  await p.waitForTimeout(1500)
  await p.screenshot({ path: `${out}/g-desktop.png` })
  await p.locator('#gallery button[aria-label^="Открыть фото"]').nth(1).click()
  await p.waitForTimeout(900)
  await p.screenshot({ path: `${out}/g-lightbox.png` })
  await p.keyboard.press('Escape')
  await p.evaluate(() => document.querySelector('#reviews button[aria-label^="Отзыв "]').scrollIntoView({ block: 'center' }))
  await p.waitForTimeout(1200)
  await p.screenshot({ path: `${out}/g-avito.png` })
  const m = await b.newContext({ ...devices['iPhone 13'], deviceScaleFactor: Number(scale) })
  await m.addInitScript(init)
  const mp = await m.newPage()
  await mp.goto('http://localhost:4173/', { waitUntil: 'networkidle' })
  await mp.evaluate(() => document.getElementById('gallery').scrollIntoView())
  await mp.waitForTimeout(1500)
  await mp.screenshot({ path: `${out}/g-mobile.png` })
  await b.close()
})()
